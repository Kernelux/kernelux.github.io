#!/usr/bin/env node
'use strict';
/*
 * SliceKit build.
 *
 *   node tools/build.js
 *
 * - Bundles core/*.js + max/glue.js into dist/slicekit.js (one file, no IIFE,
 *   tiny CommonJS shim). The footer declares the Max entry points.
 * - Copies max/ui.js to dist/slicekit-ui.js (when it exists).
 * - Runs tools/build-patchers.js (its exported build()) when it exists.
 *
 * Programmatic use (tests):
 *   var b = require('./tools/build');
 *   b.bundle()                         -> the bundle source as a string
 *   b.build({ outDir, patchers:false }) -> writes files, returns { files: [...] }
 */

var fs = require('fs');
var path = require('path');

var ROOT = path.resolve(__dirname, '..');

// Order only matters for readability; the shim resolves modules lazily.
var MODULES = [
  'core/fft.js',
  'core/prng.js',
  'core/slicing.js',
  'core/features.js',
  'core/model.js',
  'core/engine.js',
  'max/glue.js'
];

var SHIM = [
  '// ---- CommonJS shim (Max has no require) ----',
  'var __sk = { defs: {}, cache: {} };',
  '',
  '__sk.define = function (id, factory) {',
  '  __sk.defs[id] = factory;',
  '};',
  '',
  '// Resolve a require() string against the id of the requiring module.',
  '__sk.resolve = function (fromId, request) {',
  '  var parts = request.charAt(0) === "." ? fromId.split("/").slice(0, -1) : [];',
  '  var segs = request.split("/");',
  '  var i, id;',
  '  for (i = 0; i < segs.length; i++) {',
  '    if (segs[i] === "" || segs[i] === ".") { continue; }',
  '    if (segs[i] === "..") { parts.pop(); } else { parts.push(segs[i]); }',
  '  }',
  '  id = parts.join("/");',
  '  if (!__sk.defs[id] && __sk.defs[id + ".js"]) { id = id + ".js"; }',
  '  return id;',
  '};',
  '',
  '__sk.load = function (id) {',
  '  var module, factory;',
  '  if (__sk.cache[id]) { return __sk.cache[id].exports; }',
  '  factory = __sk.defs[id];',
  '  if (!factory) { throw new Error("SliceKit bundle: module not found: " + id); }',
  '  module = { exports: {}, id: id };',
  '  __sk.cache[id] = module;',
  '  factory.call(module.exports, module, module.exports, function (request) {',
  '    return __sk.load(__sk.resolve(id, request));',
  '  });',
  '  return module.exports;',
  '};',
  ''
].join('\n');

var FOOTER = [
  '// ---- Max entry points ----',
  'inlets = 1;',
  'outlets = 4;',
  'autowatch = 0;',
  '',
  'var __skGlue = null;',
  'try {',
  '  __skGlue = __sk.load("max/glue.js");',
  '} catch (e) {',
  '  post("SliceKit: failed to load: " + e + (e && e.stack ? "\\n" + e.stack : "") + "\\n");',
  '}',
  '',
  'function __skArgs(a) { return Array.prototype.slice.call(a); }',
  '',
  'function loadbang() { if (__skGlue) { __skGlue.dispatch("loadbang", []); } }',
  'function bang() { if (__skGlue) { __skGlue.dispatch("bang", []); } }',
  'function msg_int(v) { if (__skGlue) { __skGlue.dispatch("msg_int", [v]); } }',
  'function msg_float(v) { if (__skGlue) { __skGlue.dispatch("msg_float", [v]); } }',
  'function list() { if (__skGlue) { __skGlue.dispatch("list", __skArgs(arguments)); } }',
  'function anything() { if (__skGlue) { __skGlue.dispatch(messagename, __skArgs(arguments)); } }',
  'function notifydeleted() { if (__skGlue) { __skGlue.cleanup(); } }',
  ''
].join('\n');

function readModule(rel, root) {
  var file = path.join(root, rel);
  if (!fs.existsSync(file)) {
    throw new Error('build: missing module ' + rel + ' (' + file + ')');
  }
  return fs.readFileSync(file, 'utf8');
}

/** Builds the bundle source. opts: { root, banner (string, default timestamp) } */
function bundle(opts) {
  opts = opts || {};
  var root = opts.root || ROOT;
  var banner = opts.banner !== undefined ? opts.banner : 'built ' + new Date().toISOString();
  var out = [];
  var i, src;

  out.push('/* SliceKit bundle (core + glue). ' + banner + '. Generated by tools/build.js, do not edit. */');
  out.push(SHIM);
  for (i = 0; i < MODULES.length; i++) {
    src = readModule(MODULES[i], root).replace(/\r\n/g, '\n');
    out.push('// ---- module: ' + MODULES[i] + ' ----');
    out.push('__sk.define(' + JSON.stringify(MODULES[i]) + ', function (module, exports, require) {');
    out.push(src.replace(/\s+$/, ''));
    out.push('});');
    out.push('');
  }
  out.push(FOOTER);
  return out.join('\n');
}

/**
 * Writes dist files. opts: { root, outDir, patchers (default true), log (default console.log) }
 * Returns { files: [paths written], warnings: [strings] }.
 */
function build(opts) {
  opts = opts || {};
  var root = opts.root || ROOT;
  var outDir = opts.outDir || path.join(root, 'dist');
  var say = opts.log || function (s) { console.log(s); };
  var files = [];
  var warnings = [];
  var uiSrc, patchersFile, patchers, res;

  // Merge the file list / warnings reported by build-patchers into ours.
  function collect(r) {
    var i;
    if (r && Array.isArray(r.files)) {
      for (i = 0; i < r.files.length; i++) { files.push(r.files[i]); }
    }
    if (r && Array.isArray(r.warnings)) {
      for (i = 0; i < r.warnings.length; i++) { warnings.push('build-patchers: ' + r.warnings[i]); }
    }
  }

  fs.mkdirSync(outDir, { recursive: true });

  var bundleFile = path.join(outDir, 'slicekit.js');
  fs.writeFileSync(bundleFile, bundle({ root: root }));
  files.push(bundleFile);
  say('wrote ' + path.relative(root, bundleFile));

  uiSrc = path.join(root, 'max', 'ui.js');
  if (fs.existsSync(uiSrc)) {
    var uiOut = path.join(outDir, 'slicekit-ui.js');
    fs.copyFileSync(uiSrc, uiOut);
    files.push(uiOut);
    say('wrote ' + path.relative(root, uiOut));
  } else {
    warnings.push('max/ui.js not found, skipped dist/slicekit-ui.js');
  }

  if (opts.patchers !== false) {
    patchersFile = path.join(root, 'tools', 'build-patchers.js');
    if (fs.existsSync(patchersFile)) {
      patchers = require(patchersFile);
      if (patchers && typeof patchers.build === 'function') {
        res = patchers.build({ root: root, dist: outDir, outDir: outDir });
        say('ran tools/build-patchers.js');
        if (res && typeof res.then === 'function') {
          // build() is allowed to be async; the CLI waits for it.
          return res.then(function (r) {
            collect(r);
            return { files: files, warnings: warnings };
          });
        }
        collect(res);
      } else {
        warnings.push('tools/build-patchers.js does not export build(), skipped');
      }
    } else {
      warnings.push('tools/build-patchers.js not found, skipped patchers');
    }
  }
  return { files: files, warnings: warnings };
}

module.exports = {
  MODULES: MODULES,
  bundle: bundle,
  build: build,
  ROOT: ROOT
};

if (require.main === module) {
  Promise.resolve(build()).then(function (r) {
    var i;
    for (i = 0; i < r.warnings.length; i++) { console.warn('warning: ' + r.warnings[i]); }
  }).catch(function (e) {
    console.error('build failed: ' + (e && e.stack ? e.stack : e));
    process.exitCode = 1;
  });
}
